"""Write the table of the images each game plugin opens into the Supported games pages (English and Ukrainian).

The rows come from the ``supported_images`` list of every plugin's ``config.json``, so the page cannot drift from what the
plugins declare. Only the block between the two markers is written. ``--check`` exits 1 when a page is stale.

    python scripts/supported_images_page.py --write
    python scripts/supported_images_page.py --check
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, List

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from core.project_library.supported_images import normalise  # noqa: E402

START = "<!-- supported-images:start -->"
END = "<!-- supported-images:end -->"
SKIPPED_PLUGINS = frozenset({"default_plugin"})   # the template for new games, not a game

PAGES = {
    "en": (REPO / "docs" / "wiki" / "Supported_Games.md", "## Games by platform"),
    "uk": (REPO / "docs" / "wiki" / "uk" / "Supported_Games.md", "## Ігри за платформою"),
}

TEXT = {
    "en": {
        "title": "## Images each plugin opens",
        "intro": ("Each plugin opens the images listed here. When you add an image, the wizard matches its ID and region "
                  "with this list. A row that says **Not checked by ID** means the plugin does not read an ID yet. "
                  "The source is the `supported_images` list in each plugin's `config.json`."),
        "head": ["Game", "Kind", "ID", "Region", "Note"],
        "kind": {"disc": "Disc ID", "title": "Title ID", "code": "Product code", "serial": "Serial",
                 "name": "ROM name", "hash": "SHA-1 of the ROM", "unchecked": "Not checked by ID",
                 "any": "Any file"},
        "region": {},
    },
    "uk": {
        "title": "## Образи, які відкриває кожен плагін",
        "intro": ("Кожен плагін відкриває лише образи з цього списку. Коли ви додаєте образ, майстер порівнює його "
                  "ідентифікатор і регіон зі списком. Рядок **Ідентифікатор не перевіряється** означає, що плагін ще "
                  "не читає ідентифікатор. Джерело: список `supported_images` у `config.json` кожного плагіна."),
        "head": ["Гра", "Тип", "Ідентифікатор", "Регіон", "Примітки"],
        "kind": {"disc": "ID диска", "title": "Title ID", "code": "Код продукту", "serial": "Серійний номер",
                 "name": "Назва в ROM", "hash": "SHA-1 образу ROM", "unchecked": "ID не перевіряється",
                 "any": "Будь-який файл"},
        "region": {"USA": "США", "EUR": "Європа", "JPN": "Японія", "USA, Europe": "США, Європа",
                   "All regions": "Усі регіони", "Not stated": "Не вказано"},
    },
}


def declarations() -> List[Dict[str, str]]:
    """Every plugin's declarations, one dict per row, sorted by the game's name."""
    rows: List[Dict[str, str]] = []
    for config in sorted((REPO / "plugins").glob("*/config.json")):
        if config.parent.name in SKIPPED_PLUGINS:
            continue
        data = json.loads(config.read_text(encoding="utf-8"))
        name = str(data.get("display_name") or config.parent.name)
        for entry in normalise(data.get("supported_images")):
            rows.append({"game": name, **entry})
    rows.sort(key=lambda row: row["game"].casefold())   # sorted is stable: a game keeps its declaration order
    return rows


def _cell(text: str) -> str:
    return text.replace("|", "/").strip() or "—"


def render(lang: str) -> str:
    """The block for one page language, markers included."""
    text = TEXT[lang]
    lines = [START, "<!-- Generated by scripts/supported_images_page.py from plugins/*/config.json. Do not edit by hand. -->",
             "", text["title"], "", text["intro"], "",
             "| " + " | ".join(text["head"]) + " |", "|" + "---|" * len(text["head"])]
    for row in declarations():
        kind = text["kind"].get(row["kind"], row["kind"])
        ident = row["id"]
        region = text["region"].get(row["region"], row["region"])
        lines.append(f"| {_cell(row['game'])} | {_cell(kind)} | {_cell(ident)} | {_cell(region)} | {_cell(row['note'])} |")
    lines += ["", END]
    return "\n".join(lines) + "\n"


def updated_page(lang: str, current: str) -> str:
    """The page with its block replaced; the block goes before the platform tables when the markers are missing."""
    block = render(lang)
    if START in current and END in current:
        head, _, rest = current.partition(START)
        _, _, tail = rest.partition(END)
        return head + block.rstrip("\n") + tail
    anchor = PAGES[lang][1]
    if anchor not in current:
        raise SystemExit(f"{lang}: no '{anchor}' heading to put the block before")
    head, _, tail = current.partition(anchor)
    return head + block + "\n" + anchor + tail


def main(argv: List[str]) -> int:
    if "--write" not in argv and "--check" not in argv:
        print(__doc__)
        return 2
    stale = []
    for lang, (path, _anchor) in PAGES.items():
        current = path.read_text(encoding="utf-8")
        wanted = updated_page(lang, current)
        if wanted != current:
            stale.append(str(path))
            if "--write" in argv:
                path.write_text(wanted, encoding="utf-8", newline="")
    if "--check" in argv and stale:
        print("stale: run python scripts/supported_images_page.py --write\n" + "\n".join(stale))
        return 1
    print("written" if "--write" in argv else "current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
